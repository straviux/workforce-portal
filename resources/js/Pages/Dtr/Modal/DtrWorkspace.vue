function buildOrderedSignatoryDetailLines(titles, office, showDesignation = true, showOffice = true, infoOrder = 'designation_first') {
    const designationLines = showDesignation ? formatPlainList(titles) : [];
    const officeLines = showOffice && formatPlainText(office) ? [formatPlainText(office)] : [];

    return uniqueTextLines(infoOrder === 'office_first'
        ? [...officeLines, ...designationLines]
        : [...designationLines, ...officeLines]);
}

function uniqueTextLines(lines) {
    const seen = new Set();

    return (lines ?? [])
        .map((line) => String(line ?? '').trim())
        .filter((line) => {
            if (!line) {
                return false;
            }

            const key = line.toLowerCase();
            if (seen.has(key)) {
                return false;
            }

            seen.add(key);
            return true;
        });
}

function parseDateValue(value) {
    if (!value) return null;

    const parsed = dayjs(value);
    return parsed.isValid() ? parsed.toDate() : null;
}

function getBlockedEventsInRange(startValue, endValue) {
    if (!startValue || !endValue) return [];

    const start = dayjs(startValue).startOf('day');
    const end = dayjs(endValue).endOf('day');

    return (props.calendarEvents ?? [])
        .filter((event) => {
            const eventDate = dayjs(event.event_date);
            return eventDate.isValid() && !eventDate.isBefore(start, 'day') && !eventDate.isAfter(end, 'day');
        })
        .sort((left, right) => left.event_date.localeCompare(right.event_date));
}

function buildDtrDocumentRows(startValue, endValue, workDays, rows, blockedEvents = []) {
    if (!startValue || !endValue) return [];

    const selectedDays = new Set((workDays ?? []).map((day) => String(day).toLowerCase()));
    const blockedEventMap = new Map(blockedEvents.map((event) => [event.event_date, event]));
    const valuesByDate = new Map((rows ?? []).map((row) => [row.work_date, row]));
    const documentRows = [];
    let cursor = dayjs(startValue).startOf('day');
    const end = dayjs(endValue).startOf('day');

    while (!cursor.isAfter(end, 'day')) {
        const workDate = cursor.format('YYYY-MM-DD');
        const weekday = cursor.format('dddd').toLowerCase();
        const blockedEvent = blockedEventMap.get(workDate);

        if (blockedEvent) {
            documentRows.push({
                key: `special-${workDate}`,
                kind: blockedEvent.event_type === 'work_suspension' ? 'work_suspension' : 'special',
                day_number: cursor.date(),
                label: blockedEvent.event_type === 'work_suspension' ? 'WORK SUSPENSION' : 'HOLIDAY',
            });
            cursor = cursor.add(1, 'day');
            continue;
        }

        if (!selectedDays.has(weekday)) {
            documentRows.push({
                key: `special-${workDate}`,
                kind: 'offday',
                day_number: cursor.date(),
                label: cursor.format('dddd').toUpperCase(),
            });
            cursor = cursor.add(1, 'day');
            continue;
        }

        const travelLabel = formatPlainText(valuesByDate.get(workDate)?.travel_label);

        if (travelLabel) {
            const runCursors = [cursor];
            let next = cursor.add(1, 'day');

            // Extend the run while adjacent days are still scheduled work days
            // carrying the exact same travel note — each keeps its own day row,
            // only the note cell merges (rowspan) across the run.
            while (!next.isAfter(end, 'day')) {
                const nextDate = next.format('YYYY-MM-DD');
                const nextWeekday = next.format('dddd').toLowerCase();

                if (blockedEventMap.has(nextDate) || !selectedDays.has(nextWeekday)) break;
                if (formatPlainText(valuesByDate.get(nextDate)?.travel_label) !== travelLabel) break;

                runCursors.push(next);
                next = next.add(1, 'day');
            }

            runCursors.forEach((dayCursor, index) => {
                documentRows.push({
                    key: `travel-${dayCursor.format('YYYY-MM-DD')}`,
                    kind: 'travel',
                    day_number: dayCursor.date(),
                    label: index === 0 ? `OB - ${travelLabel}` : null,
                    rowspan: index === 0 ? runCursors.length : null,
                    merged: index !== 0,
                });
            });

            cursor = runCursors[runCursors.length - 1].add(1, 'day');
            continue;
        }

        documentRows.push({
            key: `work-${workDate}`,
            kind: 'work',
            day_number: cursor.date(),
            values: valuesByDate.get(workDate) ?? createEmptyDraftRow(workDate),
        });

        cursor = cursor.add(1, 'day');
    }

    return documentRows;
}

function formatDateForApi(value) {
    return value ? dayjs(value).format('YYYY-MM-DD') : '';
}

function formatShortDate(value) {
    return dayjs(value).format('MMM D');
}

function formatWeekdayLabel(value) {
    return dayjs(value).format('ddd').toUpperCase();
}

function formatTimeLabel(value) {
    return dayjs(`2000-01-01T${value}`).format('h:mm A');
}

function formatDtrPeriodLabel(startValue, endValue) {
    if (!startValue || !endValue) return '—';

    const start = dayjs(startValue);
    const end = dayjs(endValue);

    if (!start.isValid() || !end.isValid()) return '—';

    if (start.year() === end.year()) {
        if (start.month() === end.month()) {
            return `${start.format('MMMM').toUpperCase()} ${start.date()}-${end.date()}, ${end.format('YYYY')}`;
        }

        return `${start.format('MMMM').toUpperCase()} ${start.date()}-${end.format('MMMM').toUpperCase()} ${end.date()}, ${end.format('YYYY')}`;
    }

    return `${start.format('MMMM').toUpperCase()} ${start.date()}, ${start.format('YYYY')} - ${end.format('MMMM').toUpperCase()} ${end.date()}, ${end.format('YYYY')}`;
}

function formatUpperText(value) {
    const text = String(value ?? '').trim();
    return text ? text.toUpperCase() : '';
}

function formatUpperList(values) {
    return (Array.isArray(values) ? values : [])
        .map((value) => formatUpperText(value))
        .filter(Boolean);
}

function formatPlainText(value) {
    return String(value ?? '').trim();
}

function formatPlainList(values) {
    return (Array.isArray(values) ? values : [])
        .map((value) => formatPlainText(value))
        .filter(Boolean);
}

function formatDayLabel(value) {
    const match = weekdayOptions.find((option) => option.value === value);
    return match?.label ?? value;
}

function formatReportRange(report) {
    return `${dayjs(report.period_start_date).format('MMM D, YYYY')} - ${dayjs(report.period_end_date).format('MMM D, YYYY')}`;
}

function formatCreatedAt(value) {
    return value ? dayjs(value).format('MMM D, YYYY h:mm A') : 'Saved';
}

