    if (!canOpenGenerateDialog.value) return;

    resetReportEditState();
    draftValues.value = [];
    showGenerateDialog.value = true;
    rebuildDraftValues();
}

async function openSavedReportEditor(report) {
    if (!props.canManage || props.isSavingReport || props.isDeletingReport) return;

    loadingEditorReportId.value = report.id;

    try {
        const { data } = await axios.get(savedReportEndpoint(report.id));
        const reportDetail = data.data;

        isHydratingReport.value = true;
        editingReportId.value = report.id;
        generation.work_days = [...(reportDetail.work_days ?? [])];
        generation.period_start_date = parseDateValue(reportDetail.period_start_date);
        generation.period_end_date = parseDateValue(reportDetail.period_end_date);
        applyOfficeHeadSelection(reportDetail.office_head_signatory_id, reportDetail.signatory_titles ?? []);
        signatoryNameUnderline.value = reportDetail.signatory_name_underline !== false;
        signatoryShowDesignation.value = reportDetail.signatory_show_designation !== false;
        signatoryShowOffice.value = reportDetail.signatory_show_office !== false;
        signatoryInfoOrder.value = reportDetail.signatory_info_order === 'office_first' ? 'office_first' : 'designation_first';
        draftValues.value = cloneDraftValues(reportDetail.daily_values ?? []);
        showGenerateDialog.value = true;
    } catch (error) {
        resetReportEditState();
        draftValues.value = [];
        toast.add({
            severity: 'error',
            summary: 'Error',
            detail: error.response?.data?.message ?? 'Could not load the saved DTR for editing.',
            life: 4000,
        });
    } finally {
        isHydratingReport.value = false;
        loadingEditorReportId.value = null;
    }
}

function deleteSavedReport(report) {
    if (!props.canManage || props.isSavingReport || props.isDeletingReport) return;

    const confirmed = window.confirm(`Delete the DTR record for ${formatReportRange(report)}?`);

    if (!confirmed) return;

    deletingReportId.value = report.id;
    emit('delete-report', { report_id: report.id }, {
        onSuccess: () => {
            if (editingReportId.value === report.id) {
                closeGenerateDialog();
            }

            deletingReportId.value = null;
        },
        onError: () => {
            deletingReportId.value = null;
        },
    });
}

async function openSavedReportPreview(report) {
    previewingReportId.value = report.id;

    try {
        const { data } = await axios.get(savedReportEndpoint(report.id));
        const reportDetail = data.data;
        const blockedEvents = getBlockedEventsInRange(reportDetail.period_start_date, reportDetail.period_end_date);
        const documentRows = buildDtrDocumentRows(
            reportDetail.period_start_date,
            reportDetail.period_end_date,
            reportDetail.work_days ?? [],
            reportDetail.daily_values ?? [],
            blockedEvents,
        );
        const reportHtml = renderVueTemplate(DtrReportTemplate, {
            documentRows,
            preparedByOffice: preparedByOffice.value,
            preparedByName: preparedByName.value,
            preparedByTitle: preparedByTitle.value,
            reviewerName: formatPlainText(reportDetail.signatory_name) || reviewerName.value,
            reviewerTitles: reportDetail.office_head_signatory_id
                ? formatPlainList(reportDetail.signatory_titles)
                : reviewerTitles.value,
            reviewerOffice: formatPlainText(reportDetail.signatory_office) || reviewerOffice.value,
            reviewerNameUnderline: reportDetail.signatory_name_underline !== false,
            reviewerShowDesignation: reportDetail.signatory_show_designation !== false,
            reviewerShowOffice: reportDetail.signatory_show_office !== false,
            reviewerInfoOrder: reportDetail.signatory_info_order === 'office_first' ? 'office_first' : 'designation_first',
            documentPeriodLabel: formatDtrPeriodLabel(reportDetail.period_start_date, reportDetail.period_end_date),
        });
        const safeName = String(props.subject?.display_name ?? `DTR_${report.id}`).replace(/\s+/g, '_');
        const title = `DTR-${safeName}-${dayjs(reportDetail.period_start_date).format('YYYYMMDD')}`;
        const twoUpHtml = `<div class="dtr-print-sheet"><div class="dtr-card">${reportHtml}</div><div class="dtr-card">${reportHtml}</div></div>`;
        const bodyHtml = `<style>@media screen { body { font-family: Arial, Helvetica, sans-serif; } } @media print { body { padding: 0; font-family: Arial, Helvetica, sans-serif; } } ${dtrReportTemplateCss}</style>${twoUpHtml}`;

        pdfPreview.title = title;
        pdfPreview.size = 'a4';
        pdfPreview.html = buildHtmlDoc(bodyHtml, title, 'a4');
        pdfPreview.show = true;
    } catch (error) {
        toast.add({
            severity: 'error',
            summary: 'Error',
            detail: error.response?.data?.message ?? 'Could not open the saved DTR preview.',
            life: 4000,
        });
    } finally {
        previewingReportId.value = null;
    }
}

function emitSaveReport() {
    if (!canRunGenerateAction.value) return;

    const payload = {
        period_start_date: formatDateForApi(generation.period_start_date),
        period_end_date: formatDateForApi(generation.period_end_date),
        office_head_id: selectedOfficeHeadId.value,
        signatory_titles: [...selectedOfficeHeadTitles.value],
        signatory_name_underline: signatoryNameUnderline.value,
        signatory_show_designation: signatoryShowDesignation.value,
        signatory_show_office: signatoryShowOffice.value,
        signatory_info_order: signatoryInfoOrder.value,
        work_days: [...generation.work_days],
        daily_values: draftValues.value.map((row) => ({
            work_date: row.work_date,
            am_arrival: row.am_arrival || null,
            am_departure: row.am_departure || null,
            pm_arrival: row.pm_arrival || null,
            pm_departure: row.pm_departure || null,
            undertime_hours: Number(row.undertime_hours) || 0,
            undertime_minutes: Number(row.undertime_minutes) || 0,
            travel_label: formatPlainText(row.travel_label) || null,
        })),
    };

    if (isEditingReport.value) {
        emit('update-report', {
            report_id: editingReportId.value,
            ...payload,
        }, {
            onSuccess: () => {
                closeGenerateDialog();
            },
        });

        return;
    }

    emit('save-report', payload);
}

