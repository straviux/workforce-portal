function autoFillRandomHours() {
    if (!props.canManage || props.isSavingReport || !draftValues.value.length) return;

    const [pmDepartureStart, pmDepartureEnd] = activePmDepartureRange.value;

    draftValues.value = draftValues.value.map((row) => (row.travel_label ? row : {
        ...row,
        am_arrival: randomTimeBetween(...RANDOM_TIME_RANGES.am_arrival),
        am_departure: randomTimeBetween(...RANDOM_TIME_RANGES.am_departure),
        pm_arrival: randomTimeBetween(...RANDOM_TIME_RANGES.pm_arrival),
        pm_departure: randomTimeBetween(pmDepartureStart, pmDepartureEnd),
        undertime_hours: 0,
        undertime_minutes: 0,
    }));

    toast.add({
        severity: 'success',
        summary: 'Auto-filled',
        detail: `Randomized ${draftValues.value.length} work day${draftValues.value.length === 1 ? '' : 's'} within official hours, with no undertime.`,
        life: 3000,
    });
}

function randomTimeBetween(startTime, endTime) {
    const toMinutes = (time) => {
        const [hours, minutes] = time.split(':').map(Number);
        return hours * 60 + minutes;
    };

    const startMinutes = toMinutes(startTime);
    const endMinutes = toMinutes(endTime);
    const randomMinutes = startMinutes + Math.floor(Math.random() * (endMinutes - startMinutes + 1));

    const hours = Math.floor(randomMinutes / 60);
    const minutes = randomMinutes % 60;

    return `${String(hours).padStart(2, '0')}:${String(minutes).padStart(2, '0')}`;
}

function buildWorkDates() {
    const start = dayjs(generation.period_start_date);
    const end = dayjs(generation.period_end_date);
    const selectedDays = new Set(generation.work_days);
    const dates = [];
    let cursor = start.startOf('day');

    while (!cursor.isAfter(end, 'day')) {
        const currentDate = cursor.format('YYYY-MM-DD');

        if (selectedDays.has(cursor.format('dddd').toLowerCase()) && !blockedDateSet.value.has(currentDate)) {
            dates.push(currentDate);
        }

        cursor = cursor.add(1, 'day');
    }

    return dates;
}

